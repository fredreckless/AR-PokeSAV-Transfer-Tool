"""
Lab edition (v3) = Reckless edition + a safe remote-debugging "lab".

New USB commands (previously "unknown command"):
  0x04 LAB_SETADDR  arg = upload address; must be 4-aligned and inside the
                    staging window, otherwise rejected (reply 0x3F)
  0x05 LAB_POKE     arg = 32-bit word written at the cursor (cursor must stay
                    inside the window), reply 0x05 + new cursor
  0x06 LAB_EXEC     arg = 30-bit parameter. Runs the staged program and sends
                    back what it produced through Datel's normal send routine.

A staged program is: 'RKL1' magic, code length, CRC-32 of the code, then Thumb
code. The firmware refuses to run it unless the magic, length and CRC match.
It runs from RAM via a trampoline that pauses interrupts, and afterwards
ALWAYS switches the DUO's own program back in (with the same guard as v2:
if that fails it waits in RAM instead of returning).

Programs are generated by the PC tool from a small script interpreter
(LAB_INTERP below) whose write operations are restricted to:
  * the mapping register 0x0800009C and WAITCNT 0x04000204 (16-bit), and
  * save-chip command addresses 0x0E005555 / 0x0E002AAA / 0x0E000000 (8-bit),
    refusing 0x80 and 0xA0 - the values that begin an erase or a program.
Anything else stops the script with 'ERR!'.
"""
import struct, zlib
from build_patch import (BASE, PAD_END, JUMPTABLE, STUB_BL, MEMCPY, RESTORE_FLASH_FNS,
                         BUFFER, STUB_AT, PREP_AT, assemble, bl)
import build_patch2, build_reckless

SENDFILE = 0x08007188
USB_SEND8 = 0x0800C29C
CRC32_FN = 0x080065D0
LOOP = 0x08007454

STAGE_LO, STAGE_HI = 0x02038000, 0x0203B000
CURSOR = 0x02037FFC
MAGIC = 0x314C4B52            # 'RKL1'
MAX_OUT = 0x20000

LAB_PREP_AT = 0x0801EE40
LAB_TRAMP_AT = 0x0801EF00

TAIL_AT = 0x0801ED00          # shared reject/reply code
SETADDR_AT = 0x0801ED80
POKE_AT = 0x0801EDC0
EXEC_AT = 0x0801EE00

ASM_LAB_TAIL = f"""rej:
    movs r0, #0x3F
    ldr  r1, lit_bad
reply:
    sub  sp, #8
    mov  r2, sp
    movs r3, #0x53
    strb r3, [r2]
    movs r3, #0x42
    strb r3, [r2, #1]
    movs r3, #0x57
    strb r3, [r2, #2]
    strb r0, [r2, #3]
    str  r1, [r2, #4]
    mov  r0, sp
    bl   {USB_SEND8:#x}
    add  sp, #8
    ldr  r0, lit_loop
    bx   r0
    .align 2
lit_bad:    .word 0x00000BAD
lit_loop:   .word {LOOP | 1:#x}
"""
REJ, REPLY = TAIL_AT, TAIL_AT + 4

ASM_SETADDR = f"""lab_setaddr:
    ldr  r0, lit_lo
    cmp  r5, r0
    blo  {REJ:#x}
    ldr  r0, lit_hi
    cmp  r5, r0
    bhs  {REJ:#x}
    lsls r0, r5, #30
    bne  {REJ:#x}
    ldr  r0, lit_cursor
    str  r5, [r0]
    movs r0, #4
    adds r1, r5, #0
    b    {REPLY:#x}
    .align 2
lit_lo:     .word {STAGE_LO:#x}
lit_hi:     .word {STAGE_HI:#x}
lit_cursor: .word {CURSOR:#x}
"""

ASM_POKE = f"""lab_poke:
    ldr  r2, lit_cursor
    ldr  r1, [r2]
    ldr  r0, lit_lo
    cmp  r1, r0
    blo  {REJ:#x}
    ldr  r0, lit_himax
    cmp  r1, r0
    bhi  {REJ:#x}
    str  r5, [r1]
    adds r1, #4
    str  r1, [r2]
    movs r0, #5
    b    {REPLY:#x}
    .align 2
lit_lo:     .word {STAGE_LO:#x}
lit_himax:  .word {STAGE_HI - 4:#x}
lit_cursor: .word {CURSOR:#x}
"""

ASM_EXEC = f"""lab_exec:
    movs r0, #3
    lsls r1, r5, #2
    lsrs r1, r1, #2
    movs r2, #3
    lsls r2, r2, #30
    orrs r1, r2
    bl   {SENDFILE:#x}
    ldr  r0, lit_loop
    bx   r0
    .align 2
lit_loop:   .word {LOOP | 1:#x}
"""

ASM_LAB_PREP = f"""prep3:
    cmp  r0, #0
    bge  to_v2
    lsls r1, r0, #1
    bmi  exec
to_v2:
    ldr  r1, lit_v2
    bx   r1
exec:
    push {{r4, r5, lr}}
    lsls r4, r0, #2
    lsrs r4, r4, #2
    ldr  r5, lit_stage
    ldr  r0, [r5]
    ldr  r1, lit_magic
    cmp  r0, r1
    bne  bad
    ldr  r1, [r5, #4]
    cmp  r1, #0
    beq  bad
    ldr  r0, lit_maxlen
    cmp  r1, r0
    bhi  bad
    adds r0, r5, #0
    adds r0, #12
    bl   {CRC32_FN:#x}
    ldr  r1, [r5, #8]
    cmp  r0, r1
    bne  bad
    movs r0, #3
    lsls r0, r0, #24
    ldr  r1, lit_tramp
    ldr  r2, lit_tramplen
    bl   {MEMCPY:#x}
    ldr  r0, lit_buf
    adds r1, r4, #0
    adds r2, r5, #0
    adds r2, #13
    ldr  r3, lit_entry
    bl   call_r3
    adds r4, r0, #0
    movs r0, #3
    lsls r0, r0, #24
    bl   {RESTORE_FLASH_FNS:#x}
    cmp  r4, #0
    ble  bad
    ldr  r0, lit_maxout
    cmp  r4, r0
    bhi  bad
    adds r0, r4, #0
    pop  {{r4, r5}}
    pop  {{r1}}
    bx   r1
bad:
    movs r0, #1
    rsbs r0, r0, #0
    pop  {{r4, r5}}
    pop  {{r1}}
    bx   r1
call_r3:
    bx   r3
    .align 2
lit_v2:       .word {PREP_AT | 1:#x}
lit_stage:    .word {STAGE_LO:#x}
lit_magic:    .word {MAGIC:#x}
lit_maxlen:   .word {STAGE_HI - STAGE_LO - 12:#x}
lit_tramp:    .word TRAMP_ADDR
lit_tramplen: .word TRAMP_LEN
lit_buf:      .word {BUFFER:#x}
lit_entry:    .word 0x03000001
lit_maxout:   .word {MAX_OUT:#x}
"""

ASM_LAB_TRAMP = """tramp:
    push {r4, r5, r6, r7, lr}
    ldr  r4, lit_ime
    ldrh r7, [r4]
    push {r7}
    movs r5, #0
    strh r5, [r4]
    ldr  r4, lit_waitcnt
    ldrh r7, [r4]
    push {r7}
    bl   call_r2
    adds r6, r0, #0
    ldr  r4, lit_map
    ldr  r5, lit_duo
    strh r5, [r4]
    ldr  r4, lit_probe_at
    ldr  r5, [r4]
    ldr  r4, lit_probe
    cmp  r4, r5
    bne  hang
    ldr  r4, lit_waitcnt
    pop  {r7}
    strh r7, [r4]
    ldr  r4, lit_ime
    pop  {r7}
    strh r7, [r4]
    adds r0, r6, #0
    pop  {r4, r5, r6, r7}
    pop  {r1}
    bx   r1
hang:
    b    hang
call_r2:
    bx   r2
    .align 2
lit_ime:      .word 0x04000208
lit_waitcnt:  .word 0x04000204
lit_map:      .word 0x0800009C
lit_duo:      .word 0x00000120
lit_probe_at: .word PROBE_AT
lit_probe:    .word PROBE
"""

# ---- the script interpreter that every lab program carries (runs from EWRAM)
ASM_LAB_INTERP = """interp:
    push {r4, r5, r6, r7, lr}
    mov  r7, r0
    push {r0}
    adr  r6, script
next:
    ldmia r6!, {r3, r4, r5}
    cmp  r3, #0
    bne  d1
    b    finish
d1:
    cmp  r3, #1
    bne  d2
    b    op_w16
d2:
    cmp  r3, #2
    bne  d3
    b    op_w8
d3:
    cmp  r3, #3
    bne  d4
    b    op_r8
d4:
    cmp  r3, #4
    bne  d5
    b    op_r16
d5:
    cmp  r3, #5
    bne  d6
    b    op_r32
d6:
    cmp  r3, #6
    bne  d7
    b    op_delay
d7:
    cmp  r3, #7
    bne  d8
    b    op_wait16
d8:
    cmp  r3, #8
    bne  d9
    b    op_sample16
d9:
    cmp  r3, #9
    bne  d10
    b    op_sample8
d10:
    cmp  r3, #10
    bne  d11
    b    op_search
d11:
    cmp  r3, #11
    bne  d12
    b    op_crc
d12:
    b    abort
op_w16:
    ldr  r2, lit_mapreg
    cmp  r4, r2
    beq  do_w16
    ldr  r2, lit_waitreg
    cmp  r4, r2
    beq  do_w16
    b    abort
do_w16:
    strh r5, [r4]
    b    next
op_w8:
    lsls r2, r5, #24
    lsrs r2, r2, #24
    cmp  r2, #0x80
    beq  w8_bad
    cmp  r2, #0xA0
    beq  w8_bad
    ldr  r3, lit_s5555
    cmp  r4, r3
    beq  do_w8
    ldr  r3, lit_s2aaa
    cmp  r4, r3
    beq  do_w8
    ldr  r3, lit_s0000
    cmp  r4, r3
    beq  do_w8
w8_bad:
    b    abort
do_w8:
    strb r2, [r4]
    b    next
op_r8:
    cmp  r5, #0
    bne  r8_loop
    b    next
r8_loop:
    ldrb r2, [r4]
    strb r2, [r7]
    adds r4, #1
    adds r7, #1
    subs r5, #1
    bne  r8_loop
    b    next
op_r16:
    cmp  r5, #0
    bne  r16_loop
    b    next
r16_loop:
    ldrh r2, [r4]
    strb r2, [r7]
    lsrs r2, r2, #8
    strb r2, [r7, #1]
    adds r4, #2
    adds r7, #2
    subs r5, #2
    bgt  r16_loop
    b    next
op_r32:
    cmp  r5, #0
    bne  r32_loop
    b    next
r32_loop:
    ldr  r2, [r4]
    strb r2, [r7]
    lsrs r2, r2, #8
    strb r2, [r7, #1]
    lsrs r2, r2, #8
    strb r2, [r7, #2]
    lsrs r2, r2, #8
    strb r2, [r7, #3]
    adds r4, #4
    adds r7, #4
    subs r5, #4
    bgt  r32_loop
    b    next
op_delay:
    cmp  r5, #0
    bne  delay_loop
    b    next
delay_loop:
    subs r5, #1
    bne  delay_loop
    b    next
op_wait16:
    ldrh r2, [r4]
    movs r1, #0
wait_loop:
    ldrh r3, [r4]
    cmp  r3, r2
    bne  wait_done
    adds r1, #1
    cmp  r1, r5
    blo  wait_loop
wait_done:
    strb r1, [r7]
    lsrs r1, r1, #8
    strb r1, [r7, #1]
    lsrs r1, r1, #8
    strb r1, [r7, #2]
    lsrs r1, r1, #8
    strb r1, [r7, #3]
    strb r3, [r7, #4]
    lsrs r3, r3, #8
    strb r3, [r7, #5]
    adds r7, #6
    b    next
op_sample16:
    movs r0, #2
    b    sample
op_sample8:
    movs r0, #1
sample:
    lsls r1, r5, #16
    lsrs r1, r1, #16
    lsrs r5, r5, #16
    lsls r5, r5, #8
s_loop:
    cmp  r1, #0
    bne  s_go
    b    next
s_go:
    cmp  r0, #1
    beq  s_byte
    ldrh r2, [r4]
    strb r2, [r7]
    lsrs r2, r2, #8
    strb r2, [r7, #1]
    adds r7, #2
    b    s_wait
s_byte:
    ldrb r2, [r4]
    strb r2, [r7]
    adds r7, #1
s_wait:
    adds r3, r5, #0
s_dly:
    cmp  r3, #0
    beq  s_after
    subs r3, #1
    b    s_dly
s_after:
    subs r1, #1
    b    s_loop
op_search:
    ldmia r6!, {r0, r1, r2}
    push {r0, r1, r2}
    adds r5, r4, r5
    movs r3, #0
    mov  ip, r3
srch_loop:
    cmp  r4, r5
    bhs  srch_pad
    ldr  r3, [r4]
    ldr  r0, [sp]
    cmp  r3, r0
    beq  srch_hit
    ldr  r0, [sp, #4]
    cmp  r3, r0
    beq  srch_hit
    ldr  r0, [sp, #8]
    cmp  r3, r0
    beq  srch_hit
    adds r4, #4
    b    srch_loop
srch_hit:
    adds r0, r4, #0
    bl   put32
    ldr  r0, [r4]
    bl   put32
    ldr  r0, [r4, #4]
    bl   put32
    ldr  r0, [r4, #8]
    bl   put32
    adds r4, #4
    mov  r3, ip
    adds r3, #1
    mov  ip, r3
    cmp  r3, #4
    blo  srch_loop
srch_pad:
    mov  r3, ip
srch_padloop:
    cmp  r3, #4
    bhs  srch_done
    movs r0, #0
    mvns r0, r0
    bl   put32
    movs r0, #0
    mvns r0, r0
    bl   put32
    movs r0, #0
    mvns r0, r0
    bl   put32
    movs r0, #0
    mvns r0, r0
    bl   put32
    adds r3, #1
    b    srch_padloop
srch_done:
    add  sp, #12
    b    next
op_crc:
    adds r5, r4, r5
    movs r0, #0
    mvns r0, r0
    ldr  r2, lit_poly
crc_loop:
    cmp  r4, r5
    bhs  crc_done
    ldrb r1, [r4]
    adds r4, #1
    eors r0, r1
    movs r3, #8
crc_bit:
    lsrs r0, r0, #1
    bcc  crc_nox
    eors r0, r2
crc_nox:
    subs r3, #1
    bne  crc_bit
    b    crc_loop
crc_done:
    mvns r0, r0
    bl   put32
    b    next
put32:
    strb r0, [r7]
    lsrs r0, r0, #8
    strb r0, [r7, #1]
    lsrs r0, r0, #8
    strb r0, [r7, #2]
    lsrs r0, r0, #8
    strb r0, [r7, #3]
    adds r7, #4
    bx   lr
abort:
    ldr  r2, lit_err
    b    trailer
finish:
    ldr  r2, lit_done
trailer:
    strb r2, [r7]
    lsrs r2, r2, #8
    strb r2, [r7, #1]
    lsrs r2, r2, #8
    strb r2, [r7, #2]
    lsrs r2, r2, #8
    strb r2, [r7, #3]
    adds r7, #4
    pop  {r0}
    subs r0, r7, r0
    pop  {r4, r5, r6, r7}
    pop  {r1}
    bx   r1
    .align 2
lit_mapreg:  .word 0x0800009C
lit_waitreg: .word 0x04000204
lit_s5555:   .word 0x0E005555
lit_s2aaa:   .word 0x0E002AAA
lit_s0000:   .word 0x0E000000
lit_done:    .word 0x454E4F44
lit_err:     .word 0x21525245
lit_poly:    .word 0xEDB88320
    .align 2
script:
"""


def interp_code():
    import thumbcheck
    return thumbcheck.checked_assemble(assemble, ASM_LAB_INTERP, STAGE_LO + 12, "lab interpreter")


def build(src_fw, out_fw):
    fw = bytearray(src_fw)
    tail = assemble(ASM_LAB_TAIL, TAIL_AT)
    assert assemble("movs r0, #0x3F\nldr r1, [pc, #0]\n", TAIL_AT).__len__() == 4
    pieces = [(TAIL_AT, tail), (SETADDR_AT, assemble(ASM_SETADDR, SETADDR_AT)),
              (POKE_AT, assemble(ASM_POKE, POKE_AT)), (EXEC_AT, assemble(ASM_EXEC, EXEC_AT))]
    probe = struct.unpack_from("<I", fw, STUB_AT - BASE)[0]
    tramp = assemble(ASM_LAB_TRAMP.replace("PROBE_AT", hex(STUB_AT)).replace("PROBE", hex(probe)), LAB_TRAMP_AT)
    prep = assemble(ASM_LAB_PREP.replace("TRAMP_ADDR", hex(LAB_TRAMP_AT)).replace("TRAMP_LEN", hex(len(tramp))), LAB_PREP_AT)
    pieces += [(LAB_PREP_AT, prep), (LAB_TRAMP_AT, tramp)]
    pieces.sort()
    for (a1, b1), (a2, _) in zip(pieces, pieces[1:]):
        assert a1 + len(b1) <= a2, f"piece at {a1:#x} overlaps {a2:#x}"
    assert pieces[-1][0] + len(pieces[-1][1]) < PAD_END
    for at, blob in pieces:
        o = at - BASE
        assert all(x == 0xFF for x in fw[o:o + len(blob)]), f"padding at {at:#x} not empty"
        fw[o:o + len(blob)] = blob
    entries = {4: SETADDR_AT, 5: POKE_AT, 6: EXEC_AT}
    for cmd, addr in entries.items():
        ent = JUMPTABLE + (cmd - 2) * 4 - BASE
        assert struct.unpack_from("<I", fw, ent)[0] == 0x08007572, f"command {cmd:#x} slot in use"
        struct.pack_into("<I", fw, ent, addr)
    b = STUB_BL - BASE
    assert fw[b:b + 4] == bl(STUB_BL, PREP_AT)
    fw[b:b + 4] = bl(STUB_BL, LAB_PREP_AT)
    open(out_fw, "wb").write(fw)
    return bytes(fw), entries, sum(len(p) for _, p in pieces)


if __name__ == "__main__":
    v2, _ = build_patch2.build("fw.bin", "fw_patched2.bin")
    rk, _, _ = build_reckless.build(v2, "fw_reckless.bin")
    fw, entries, n = build(rk, "fw_lab.bin")
    crc = zlib.crc32(fw)
    open("duo_1.06_reckless_lab.bin", "wb").write(struct.pack("<I", crc) + fw)
    print(f"lab code {n} bytes; entries {[(hex(k), hex(v)) for k, v in entries.items()]}; update CRC {crc:08X}")
    print(f"interpreter {len(interp_code())} bytes")
